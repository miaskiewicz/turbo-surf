#!/usr/bin/env python3
"""Lay out prepared Deno candidates as a Git-consumable tree with registry-form manifests.

Pre-publication consumers `[patch.crates-io]` every candidate from one Git
revision of this tree. Manifests therefore carry no candidate paths: each
internal edge stays an exact registry requirement that the consumer's patch
table satisfies, exactly as the published archives will after Cargo's own
normalization.
"""

import argparse
import importlib.util
import json
import re
import shutil
import tomllib
from pathlib import Path


ROOT = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("deno_prepare", ROOT / "prepare.py")
prepare = importlib.util.module_from_spec(spec)
spec.loader.exec_module(prepare)
archive_spec = importlib.util.spec_from_file_location("deno_archive_check", ROOT / "check_archives.py")
archive_check = importlib.util.module_from_spec(archive_spec)
archive_spec.loader.exec_module(archive_check)
REPOSITORY = "https://github.com/miaskiewicz/turbo-surf"
README = """# turbo-surf Deno distribution candidates (generated; do not edit)

Generated by `rust/release-deps/push-candidates.sh` from turbo-surf
{source}. Seven pre-publication candidates of the named Deno family with
registry-form manifests (no candidate paths). Consumers `[patch.crates-io]`
each package from this branch at one exact `rev`; nothing here is published.
`prepared-source-identity.json` is the prepare.py receipt (candidate files
before path removal).
"""


def without_paths(text):
    """Drop dependency `path` keys only; `[lib]`/`[[bench]]` paths are targets."""
    sections = re.split(r"(?m)^(\[[^\n]+\]\n)", text)
    for index in range(1, len(sections), 2):
        if re.search(r"(?:^|\.)(?:dev-|build-)?dependencies\.[^\]]+\]", sections[index][1:]):
            sections[index + 1] = re.sub(r"(?m)^path = .*\n", "", sections[index + 1])
    result = "".join(sections)
    if tomllib.loads(result) != archive_check.normalized(tomllib.loads(text)):
        raise ValueError("Registry-form manifest changes more than dependency paths")
    return result


def manifests(root):
    found = {}
    for path in sorted(root.rglob("Cargo.toml")):
        name = tomllib.loads(path.read_text()).get("package", {}).get("name")
        if name in found:
            raise ValueError(f"Duplicate candidate package name: {name}")
        found[name] = path.parent.relative_to(root).as_posix()
    return found


def build(prepared, output, source):
    if output.exists():
        raise ValueError("Refusing to overwrite an existing candidate tree")
    shutil.copytree(prepared / "packages", output / "packages")
    for package in prepare.PACKAGES:
        manifest = output / "packages" / package.name / "Cargo.toml"
        manifest.write_text(without_paths(manifest.read_text()))
    shutil.copyfile(prepared / "prepared-source-identity.json", output / "prepared-source-identity.json")
    (output / "README.md").write_text(README.format(source=source))
    # Cargo's Git source scans every manifest in the checkout; names must be unique
    # and the closure exactly the prepared distributions.
    expected = {p.name: f"packages/{p.name}" for p in prepare.PACKAGES}
    if manifests(output) != expected:
        raise ValueError("Candidate tree closure differs from the prepared distributions")
    for package in prepare.PACKAGES:
        parsed = tomllib.loads((output / "packages" / package.name / "Cargo.toml").read_text())
        if (parsed["package"]["name"], parsed["package"]["version"]) != (package.name, package.publish):
            raise ValueError("Candidate tree identity differs")
    return expected


def patch_snippet(rev, repository=REPOSITORY):
    lines = ["[patch.crates-io]"]
    lines += [f'{p.name} = {{ git = {json.dumps(repository)}, rev = {json.dumps(rev)} }}' for p in prepare.PACKAGES]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--prepared", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--source", required=True, help="Source commit recorded in the tree README")
    args = parser.parse_args()
    print(json.dumps(build(args.prepared, args.output, args.source), indent=2))


if __name__ == "__main__":
    main()
