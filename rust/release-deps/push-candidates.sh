#!/usr/bin/env bash
# Generate the seven Deno-family candidates and commit them to the throwaway
# orphan branch that pre-publication consumers `[patch.crates-io]` by Git rev.
#
#   rust/release-deps/push-candidates.sh [--no-push]
#
# Environment: CANDIDATE_BRANCH (default consolidation/deno-candidates),
# CANDIDATE_REMOTE (default origin), DENO_ARCHIVE_DIR (private upstream archive
# directory, reused across runs; default a temporary one, populated with
# `prepare.py --download`, which verifies every archive against source-pins.json).
#
# The current checkout, index and branch are never touched: the commit is built
# with a private index. The first commit has no parent; later runs append a
# child commit (only when the tree changed), so the branch is never force-pushed.
# Prints the candidate commit SHA and the matching [patch.crates-io] table.
set -euo pipefail

push=1
if [[ "${1:-}" == "--no-push" ]]; then push=0; elif [[ $# -gt 0 ]]; then
    echo "usage: $0 [--no-push]" >&2; exit 2
fi
repo=$(git -C "$(dirname "$0")" rev-parse --show-toplevel)
cd "$repo"
branch=${CANDIDATE_BRANCH:-consolidation/deno-candidates}
remote=${CANDIDATE_REMOTE:-origin}
source_commit=$(git rev-parse HEAD)
if [[ -n "$(git status --porcelain --untracked-files=all -- rust/release-deps)" ]]; then
    echo "Release tooling (incl. deno/patches) is dirty; commit it first." >&2; exit 1
fi
work=$(mktemp -d "${TMPDIR:-/tmp}/turbo-surf-deno-candidates.XXXXXX")
[[ -n "$work" && -d "$work" ]] || { echo "mktemp failed" >&2; exit 1; }
trap 'rm -rf -- "$work"' EXIT
archives=${DENO_ARCHIVE_DIR:-$work/upstream-archives}

python3 -B rust/release-deps/deno/prepare.py --archive-dir "$archives" --download --output "$work/prepared" >&2
python3 -B rust/release-deps/deno/prepare.py --archive-dir "$archives" --output "$work/prepared" --check >&2
python3 -B rust/release-deps/deno/candidate_tree.py --prepared "$work/prepared" --output "$work/tree" --source "$source_commit" >&2

git_dir=$(git rev-parse --absolute-git-dir)
export GIT_INDEX_FILE="$work/index"
git -C "$work/tree" --git-dir="$git_dir" --work-tree=. add -A -f -- .
tree=$(git -C "$work/tree" --git-dir="$git_dir" --work-tree=. write-tree)
unset GIT_INDEX_FILE
parent=$(git rev-parse -q --verify "refs/heads/$branch^{commit}" || true)
if [[ -z "$parent" ]] && git ls-remote --exit-code --heads "$remote" "$branch" >/dev/null 2>&1; then
    git fetch -q "$remote" "refs/heads/$branch:refs/heads/$branch"
    parent=$(git rev-parse "refs/heads/$branch^{commit}")
fi
if [[ -n "$parent" && "$(git rev-parse "$parent^{tree}")" == "$tree" ]]; then
    commit=$parent
    echo "Candidate tree unchanged; reusing $commit" >&2
else
    message="chore(deno-candidates): seven Deno-family candidates from turbo-surf $source_commit

Generated by rust/release-deps/push-candidates.sh (prepare.py + candidate_tree.py).
Pre-publication only: consumers [patch.crates-io] these by Git rev; nothing is published.

Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>"
    commit=$(git commit-tree "$tree" ${parent:+-p "$parent"} -m "$message")
    git update-ref "refs/heads/$branch" "$commit" ${parent:+"$parent"}
fi
if [[ $push == 1 ]]; then
    git push -q "$remote" "refs/heads/$branch:refs/heads/$branch" >&2
fi
echo "$commit"
python3 -B - "$commit" <<'PY'
import importlib.util, sys
from pathlib import Path
spec = importlib.util.spec_from_file_location("candidate_tree", Path("rust/release-deps/deno/candidate_tree.py"))
module = importlib.util.module_from_spec(spec)
spec.loader.exec_module(module)
print(module.patch_snippet(sys.argv[1]), end="")
PY
